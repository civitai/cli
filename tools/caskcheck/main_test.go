// TestArchiveProbesCarryNoCredential is the reason this command exists at all.
//
// 🔴 A DRAFT RELEASE IS VISIBLE TO ANY REPO TOKEN, AND CI ALWAYS HAS ONE. If the
// archive request carried Authorization, the check could be answered by the very
// object whose invisibility to users IS the outage. So the archive and cask
// requests must go out as a stranger — and the assertion is only meaningful
// paired with the positive control below, that the token plumbing is live and
// DOES attach on the releases-API call. Without that control, "no Authorization
// anywhere" is equally satisfied by a checker holding no token at all.
func TestArchiveProbesCarryNoCredential(t *testing.T) {
	w := newWorld(t, "0.1.91", []string{"0.1.90"}, "v0.1.90") // red, so the API path is exercised too

	if _, err := run(t, w.checker()); err == nil {
		t.Fatal("PREMISE BROKEN: this fixture must be the failing one, or the releases-API call below is never made")
	}

	for _, got := range w.rec.authFor("/civitai/cli/releases/download/") {
		if got != "" {
			t.Errorf("an archive probe carried Authorization %q — it must ask exactly what an unauthenticated `brew install` asks", got)
		}
	}
	for _, got := range w.rec.authFor("/Casks/") {
		if got != "" {
			t.Errorf("the cask fetch carried Authorization %q; the tap is public and brew reads it anonymously", got)
		}
	}

	api := w.rec.authFor("/repos/civitai/cli/releases/latest")
	if len(api) == 0 {
		t.Fatal("POSITIVE CONTROL failed: the releases API was never called, so 'no Authorization on the archive' is vacuous")
	}
	for _, got := range api {
		if got != "Bearer fixture-token" {
			t.Errorf("the releases API call should carry the token (it buys rate limit); got %q", got)
		}
	}
}

// TestTheDiagnosticLookupCannotTurnAHealthyPipelineRed — the releases API is not
// the invariant, so its failure must not become one.
func TestTheDiagnosticLookupCannotTurnAHealthyPipelineRed(t *testing.T) {
	w := newWorld(t, "0.1.91", []string{"0.1.91"}, "v0.1.91")
	c := w.checker()
	c.latestURL = "http://127.0.0.1:1/nope" // guaranteed refused

	if _, err := run(t, c); err != nil {
		t.Fatalf("a dead releases API must not fail a pipeline whose archives are all downloadable: %v", err)
	}
}

// TestADeadDiagnosticLookupStillReportsTheRealFinding — and it must not swallow
// one either. The finding stands on the HTTP probes alone.
func TestADeadDiagnosticLookupStillReportsTheRealFinding(t *testing.T) {
	w := newWorld(t, "0.1.91", []string{"0.1.90"}, "v0.1.90")
	c := w.checker()
	c.latestURL = "http://127.0.0.1:1/nope"

	_, err := run(t, c)
	if err == nil {
		t.Fatal("the broken state went unreported because the diagnostic lookup failed")
	}
	if !strings.Contains(err.Error(), "0.1.91") || !strings.Contains(err.Error(), "unknown") {
		t.Errorf("want the finding plus an explicit 'unknown' for the un-readable diagnostic, got:\n%v", err)
	}
}
